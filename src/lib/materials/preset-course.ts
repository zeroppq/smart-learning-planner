/**
 * 优先读取 docs 目录下的正式讲义；文件缺失时退回内置的简版讲义，保证演示不空转。
 */
export function loadPresetCourseText(): string {
  try {
    const text = readFileSync(join(process.cwd(), PRESET_COURSE_RELATIVE_PATH), "utf8").trim();
    if (text.length > 500) {
      return text;
    }
  } catch {
    // 读取失败时使用内置兜底讲义
  }
  return PRESET_COURSE_FALLBACK_TEXT;
}

